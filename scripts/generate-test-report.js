const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const resultsPath = path.join(root, '.test-results.json');
const coveragePath = path.join(root, 'coverage', 'coverage-summary.json');
const reportPath = path.join(root, 'test-report.md');

if (!fs.existsSync(resultsPath) || !fs.existsSync(coveragePath)) {
    throw new Error('Run Jest with JSON results and json-summary coverage before generating the report.');
}

const results = JSON.parse(fs.readFileSync(resultsPath, 'utf8'));
const coverage = JSON.parse(fs.readFileSync(coveragePath, 'utf8')).total;
const relative = file => path.relative(root, file).replace(/\\/g, '/');
const percent = metric => `${coverage[metric].pct}%`;
const suites = results.testResults.map(suite => {
    const assertions = suite.assertionResults || [];
    const passed = assertions.filter(test => test.status === 'passed').length;
    const failed = assertions.filter(test => test.status === 'failed').length;
    return `| \`${relative(suite.name)}\` | ${passed} | ${failed} | ${failed ? 'FAILED' : 'PASSED'} |`;
}).join('\n');

const report = `# SurgeLab Test Report

> This file is generated by \`npm run test:report\`. Do not edit it manually.

Generated: ${new Date().toISOString()}

## Result

| Metric | Value |
| --- | ---: |
| Test suites | ${results.numPassedTestSuites} passed / ${results.numTotalTestSuites} total |
| Tests | ${results.numPassedTests} passed / ${results.numTotalTests} total |
| Failed tests | ${results.numFailedTests} |
| Statement coverage | ${percent('statements')} |
| Branch coverage | ${percent('branches')} |
| Function coverage | ${percent('functions')} |
| Line coverage | ${percent('lines')} |

## Suites

| Suite | Passed | Failed | Status |
| --- | ---: | ---: | --- |
${suites}

## Reproduce

Run \`npm run test:report\`. The command executes Jest, recalculates coverage, and replaces this report from machine-readable output.
`;

fs.writeFileSync(reportPath, report);
console.log(`Generated ${relative(reportPath)}`);
